# text-to-speech engines
# --------------------------------------------------------------------------
class TTSEngine:
    """Common interface for a local narration backend.

    Engines are cheap to construct and lazy about loading their model, so the
    pipeline can call :meth:`available` first and only pay the (often heavy) load
    cost when it is actually going to synthesise something.
    """

    #: Stable identifier used by ``--engine`` / ``narration_engine``.
    name: str = "tts"
    #: Human-readable label for CLI output.
    label: str = "TTS"

    def available(self) -> tuple[bool, str]:
        """Whether the backend can run here, plus a reason either way."""
        raise NotImplementedError

    def synthesise(self, text: str, out_wav: Path) -> float:
        """Render ``text`` into ``out_wav``; return the audio duration."""
        raise NotImplementedError


def _write_mono_wav(out_wav: Path, samples, sample_rate: int) -> float:
    """Write ``samples`` (torch tensor or array, float or int) as a mono WAV.

    Prefers soundfile — which VoxCPM already depends on — and falls back to scipy
    (a pocket-tts dependency) so neither backend's extra is strictly required.
    """
    import numpy as np

    out_wav.parent.mkdir(parents=True, exist_ok=True)
    arr = samples.detach().cpu().numpy() if hasattr(samples, "detach") else np.asarray(samples)
    arr = np.asarray(arr)
    if arr.ndim > 1:
        arr = arr.reshape(-1)  # engines may return (n, channels)
    if arr.dtype.kind == "f":
        peak = float(np.max(np.abs(arr))) or 1.0
        arr = (arr / peak * 32767.0 * 0.95).astype(np.int16)
    elif arr.dtype != np.int16:
        arr = arr.astype(np.int16)

    try:
        import soundfile as sf

        sf.write(str(out_wav), arr, int(sample_rate))
    except Exception:  # soundfile missing or unhappy -> scipy
        import scipy.io.wavfile

        scipy.io.wavfile.write(str(out_wav), int(sample_rate), arr)
    return probe.probe_audio_duration(out_wav)


class PocketTTS(TTSEngine):
    """Lazy wrapper around pocket-tts' Python API.

    The model (~100M params) and voice state are loaded once and kept in memory
    because ``load_model`` and ``get_state_for_audio_prompt`` are slow.
    """

    name = "pocket-tts"
    label = "pocket-tts"

    def __init__(self, voice: str = "alba", language: str = "english",
                 config_url: str | None = None):
        self.voice = voice
        self.language = language
        self.config_url = config_url
        self._model = None
        self._state = None
        self._sample_rate = 24000

    def available(self) -> tuple[bool, str]:
        try:
            import pocket_tts  # noqa: F401

            return True, "pocket_tts importable"
        except Exception as exc:
            return False, f"pocket-tts not importable: {exc}"

    def _load(self) -> None:
        if self._model is not None:
            return
        from pocket_tts import TTSModel

        kwargs = {}
        if self.config_url:
            kwargs["config"] = self.config_url
        elif self.language and self.language != "english":
            kwargs["language"] = self.language
        self._model = TTSModel.load_model(**kwargs)
        self._sample_rate = getattr(self._model, "sample_rate", 24000)
        self._state = self._model.get_state_for_audio_prompt(self.voice)

    def synthesise(self, text: str, out_wav: Path) -> float:
        """Generate speech for ``text`` into ``out_wav``; returns duration."""
        self._load()
        import numpy as np
        import scipy.io.wavfile

        out_wav.parent.mkdir(parents=True, exist_ok=True)
        audio = self._model.generate_audio(self._state, text)
        arr = audio.detach().cpu().numpy() if hasattr(audio, "detach") else np.asarray(audio)
        arr = np.asarray(arr)
        if arr.dtype != np.int16:
            peak = float(np.max(np.abs(arr))) or 1.0
            arr = (arr / peak * 32767.0 * 0.95).astype(np.int16)
        scipy.io.wavfile.write(str(out_wav), self._sample_rate, arr)
        return probe.probe_audio_duration(out_wav)


class _VoxCPMVoice:
    """Shared ``narration_voice`` interpretation for the VoxCPM backends.

    VoxCPM has no named voice catalogue.  It is driven by a *description* (voice
    design) or a *reference clip* (zero-shot cloning), so the brief's
    ``narration_voice`` is read as:

    * a path to an existing audio file -> clone that voice;
    * a phrase containing whitespace -> a voice-design prompt;
    * anything else (e.g. the pocket-tts default ``alba``) -> ignored, and the
      model's own default voice is used.
    """

    _AUDIO_SUFFIXES = {".wav", ".mp3", ".flac", ".m4a", ".ogg", ".opus"}
    #: Set by each engine's ``__init__``.
    voice: str = ""

    @property
    def reference_wav(self) -> Path | None:
        """A ``narration_voice`` that points at a real audio file means cloning."""
        if not self.voice:
            return None
        path = Path(self.voice)
        if path.suffix.lower() in self._AUDIO_SUFFIXES and path.exists():
            return path
        return None

    @property
    def voice_description(self) -> str:
        """A multi-word ``narration_voice`` is a voice-design prompt."""
        if not self.voice or self.reference_wav is not None:
            return ""
        return self.voice if any(c.isspace() for c in self.voice) else ""

    def prompt_text(self, text: str) -> str:
        """Apply the voice-design prefix VoxCPM expects, when one is set."""
        desc = self.voice_description
        return f"({desc}){text}" if desc else text


class VoxCPM(TTSEngine, _VoxCPMVoice):
    """Lazy wrapper around OpenBMB's VoxCPM (tokenizer-free diffusion TTS).

    This is the **PyTorch** backend.  It cannot be quantized: voxcpm 2.0.3's
    ``from_pretrained`` exposes no dtype or bitsandbytes hook, so it needs a GPU
    with room for the full-precision model (VoxCPM2 2B wants ~8 GB).  On a small
    card use :class:`VoxCPMGGUF` instead, which runs a quantized GGUF build.
    """

    name = "voxcpm"
    label = "VoxCPM"
    #: Default checkpoint; override with ``narration_model`` / ``--tts-model``.
    DEFAULT_MODEL = "openbmb/VoxCPM2"

    def __init__(self, voice: str = "", language: str = "english",
                 model: str | None = None, *,
                 cfg_value: float = 2.0, inference_timesteps: int = 10,
                 seed: int | None = 42, load_denoiser: bool = False):
        self.voice = (voice or "").strip()
        #: VoxCPM2 auto-detects language; kept only for interface parity.
        self.language = language
        self.model_id = model or self.DEFAULT_MODEL
        self.cfg_value = cfg_value
        self.inference_timesteps = inference_timesteps
        self.seed = seed
        self.load_denoiser = load_denoiser
        self._model = None
        self._sample_rate = 48000

    # --- engine interface -------------------------------------------------
    def available(self) -> tuple[bool, str]:
        try:
            import voxcpm  # noqa: F401
        except Exception as exc:
            return False, (
                f"voxcpm not importable: {exc} (install with "
                f"'uv sync --extra voxcpm'; it needs Python <3.13 and PyTorch). "
                f"For a small GPU, use --engine voxcpm-gguf instead."
            )
        return True, f"voxcpm importable ({self.model_id})"

    def _load(self) -> None:
        if self._model is not None:
            return
        from voxcpm import VoxCPM as _VoxCPM

        self._model = _VoxCPM.from_pretrained(
            self.model_id, load_denoiser=self.load_denoiser,
        )
        inner = getattr(self._model, "tts_model", None)
        self._sample_rate = int(getattr(inner, "sample_rate", 0) or 48000)

    def synthesise(self, text: str, out_wav: Path) -> float:
        self._load()
        kwargs: dict = {
            "text": self.prompt_text(text),
            "cfg_value": self.cfg_value,
            "inference_timesteps": self.inference_timesteps,
        }
        if self.seed is not None:
            kwargs["seed"] = self.seed
        ref = self.reference_wav
        if ref is not None:
            kwargs["reference_wav_path"] = str(ref)
        wav = self._model.generate(**kwargs)
        return _write_mono_wav(out_wav, wav, self._sample_rate)


class VoxCPMGGUF(TTSEngine, _VoxCPMVoice):
    """Narration through llama.cpp-omni's ``voxcpm2-cli`` — quantized, no PyTorch.

    This is the backend for a **small GPU**: llama.cpp-omni loads a quantized
    GGUF (Q4_K is ~1.5 GB for the full 2B model) so VoxCPM2 fits a 4 GB card,
    and it needs no Python ML stack at all — just the compiled binary and the
    weight files.

    Unlike the PyTorch backend this one is a subprocess wrapper, because
    llama.cpp-omni is a C++ runtime.  Paths come from the constructor or the
    ``MANIMATIONS_VOXCPM_*`` environment variables, so the binary can live
    outside the repo.

    The CLI takes **two** GGUF files: a BaseLM and an Acoustic stack.  Either
    pass the split files, or point ``base_lm`` at a combined single-file GGUF
    (``voxcpm2-q4_k.gguf``); when ``acoustic`` is omitted the combined layout is
    assumed.
    """

    name = "voxcpm-gguf"
    label = "VoxCPM2 (GGUF)"

    #: Defaults, relative to the repo root, matching the documented build layout.
    #: Resolved to absolute paths at construction so the subprocess works
    #: regardless of its working directory.
    DEFAULT_BIN = "build/llama.cpp-omni/build/bin/voxcpm2-cli.exe"
    DEFAULT_BASE_LM = "build/voxcpm-gguf/VoxCPM2-BaseLM-Q8_0.gguf"
    DEFAULT_ACOUSTIC = "build/voxcpm-gguf/VoxCPM2-Acoustic-F16.gguf"
    #: Layers to offload by default.  Measured on a 4 GB GTX 1650 with the Q8_0
    #: BaseLM + F16 Acoustic stack (~3.6 GB resident): 10 layers works for short
    #: text, but 12 OOMs once generation grows the AudioVAE decode graph, so 8 is
    #: the safe default.  Raise it on a bigger card; pass 0 to force CPU.
    DEFAULT_GPU_LAYERS = 8

    def __init__(self, voice: str = "", language: str = "english", *,
                 binary: str | None = None, base_lm: str | None = None,
                 acoustic: str | None = None, n_gpu_layers: int | None = None,
                 cfg_value: float = 2.0, timesteps: int = 10,
                 temperature: float = 1.0, seed: int | None = 42,
                 timeout: int = 900):
        import os

        self.voice = (voice or "").strip()
        self.language = language
        # Built artifacts default to the repo root; explicit/env paths are used
        # as given (relative to the caller's cwd, as usual).
        root = Path(__file__).resolve().parents[3]
        self.binary = Path(
            binary or os.environ.get("MANIMATIONS_VOXCPM_BIN") or root / self.DEFAULT_BIN
        )
        self.base_lm = Path(
            base_lm or os.environ.get("MANIMATIONS_VOXCPM_BASE_LM")
            or root / self.DEFAULT_BASE_LM
        )
        acoustic = acoustic or os.environ.get("MANIMATIONS_VOXCPM_ACOUSTIC")
        if acoustic:
            self.acoustic: Path | None = Path(acoustic)
        else:
            default_acoustic = root / self.DEFAULT_ACOUSTIC
            self.acoustic = default_acoustic if default_acoustic.exists() else None
        #: Layer count: explicit arg > env var > measured default for a 4 GB card.
        env_layers = os.environ.get("MANIMATIONS_VOXCPM_GPU_LAYERS")
        if n_gpu_layers is None:
            n_gpu_layers = int(env_layers) if env_layers else self.DEFAULT_GPU_LAYERS
        self.n_gpu_layers = n_gpu_layers
        self.cfg_value = cfg_value
        self.timesteps = timesteps
        self.temperature = temperature
        self.seed = seed
        self.timeout = timeout

    def available(self) -> tuple[bool, str]:
        if not self.binary.exists():
            return False, (
                f"voxcpm2-cli not found at {self.binary} — build it with "
                f"llama.cpp-omni (see build/llama.cpp-omni/build_vulkan.bat)"
            )
        if not self.base_lm.exists():
            return False, f"BaseLM GGUF not found at {self.base_lm}"
        if self.acoustic is not None and not self.acoustic.exists():
            return False, f"Acoustic GGUF not found at {self.acoustic}"
        return True, f"voxcpm2-cli ({self.base_lm.name})"

    def synthesise(self, text: str, out_wav: Path) -> float:
        import subprocess

        out_wav.parent.mkdir(parents=True, exist_ok=True)
        cmd = [
            str(self.binary),
            "-t", self.prompt_text(text),
            "-o", str(out_wav),
            "--cfg", str(self.cfg_value),
            "--timesteps", str(self.timesteps),
            "--temperature", str(self.temperature),
        ]
        if self.seed is not None:
            cmd += ["--seed", str(self.seed)]
        if self.n_gpu_layers is not None:
            cmd += ["--n-gpu-layers", str(self.n_gpu_layers)]
        ref = self.reference_wav
        if ref is not None:
            cmd += ["-r", str(ref)]
        # BaseLM is required; Acoustic is a second positional file in the split
        # layout, and omitted when a combined single-file GGUF is in use.
        cmd.append(str(self.base_lm))
        if self.acoustic is not None and self.acoustic.exists():
            cmd.append(str(self.acoustic))

        proc = subprocess.run(
            cmd, capture_output=True, text=True, timeout=self.timeout,
        )
        if proc.returncode != 0 or not out_wav.exists() or out_wav.stat().st_size == 0:
            tail = (proc.stderr or proc.stdout or "").strip().splitlines()[-3:]
            raise RuntimeError(
                f"voxcpm2-cli failed (rc={proc.returncode}): {' | '.join(tail)}"
            )
        return probe.probe_audio_duration(out_wav)


# --------------------------------------------------------------------------
# engine registry
# --------------------------------------------------------------------------
#: Canonical engine name -> class.  Aliases are folded in by
#: :func:`resolve_engine_name`; the canonical names are the ones listed in
#: :data:`manimations.config.TTS_ENGINES`.
_ENGINE_CLASSES: dict[str, type[TTSEngine]] = {
    "pocket-tts": PocketTTS,
    "voxcpm": VoxCPM,
    "voxcpm-gguf": VoxCPMGGUF,
}

_ENGINE_ALIASES = {
    "pocket": "pocket-tts",
    "pocket_tts": "pocket-tts",
    "pockettts": "pocket-tts",
    "pocket-tts": "pocket-tts",
    "vox": "voxcpm",
    "voxcpm": "voxcpm",
    "vox-gguf": "voxcpm-gguf",
    "voxcpm_gguf": "voxcpm-gguf",
    "voxcpm-gguf": "voxcpm-gguf",
    "gguf": "voxcpm-gguf",
}

#: Engine used when neither the brief nor the CLI names one.
DEFAULT_ENGINE = "pocket-tts"


def resolve_engine_name(name: str | None) -> str:
    """Fold an engine alias onto its canonical name (default: pocket-tts)."""
    if not name or not str(name).strip():
        return DEFAULT_ENGINE
    key = str(name).strip().lower()
    return _ENGINE_ALIASES.get(key, key)


def get_engine(name: str | None, *, voice: str | None = None,
               language: str = "english", model: str | None = None,
               config_url: str | None = None, **kwargs) -> TTSEngine:
    """Build the narration engine for ``name`` (alias-tolerant).

    Unknown names raise :class:`ValueError` rather than silently falling back, so
    a typo in a brief is caught at validation time instead of producing silence.
    """
    resolved = resolve_engine_name(name)
    cls = _ENGINE_CLASSES.get(resolved)
    if cls is None:
        known = ", ".join(sorted(_ENGINE_CLASSES))
        raise ValueError(f"unknown narration engine {name!r} (known: {known})")
    if cls is PocketTTS:
        return PocketTTS(voice=voice or "alba", language=language,
                         config_url=config_url)
    if cls is VoxCPMGGUF:
        return VoxCPMGGUF(voice=voice or "", language=language, **kwargs)
    # VoxCPM (PyTorch): reject backend-specific options rather than ignoring
    # them, so e.g. --gpu-layers against the wrong engine fails loudly.
    if kwargs:
        raise ValueError(
            f"engine {resolved!r} does not accept {sorted(kwargs)}"
        )
    return VoxCPM(voice=voice or "", language=language, model=model)


# --------------------------------------------------------------------------
# project-level narration
# --------------------------------------------------------------------------
def synthesise_narration(
    project: ProjectConfig,
    *,
    voice: str | None = None,
    language: str = "english",
    config_url: str | None = None,
    only: list[str] | None = None,
    engine: TTSEngine | None = None,
    engine_name: str | None = None,
    model: str | None = None,
    **engine_kwargs,
) -> list[NarrationClip]:
    """Generate one WAV per scene.  Missing scenes are reported, not faked.

    The backend is, in order of precedence: ``engine`` (an explicit instance,
    used by tests), ``engine_name`` (``--engine``), then the project's
    ``narration_engine``.
    """
    voice = voice or project.narration_voice
    name = engine_name or getattr(project, "narration_engine", None) or DEFAULT_ENGINE
    engine = engine or get_engine(
        name, voice=voice, language=language, config_url=config_url,
        model=model or getattr(project, "narration_model", None),
        **engine_kwargs,
    )
    ok, detail = engine.available()
    clips: list[NarrationClip] = []

    for spec in project.scenes:
        if only and spec.id not in only:
            continue
        if not spec.narration.strip():
            clips.append(NarrationClip(spec.id, None, 0.0, "", False, "no narration text"))
            continue
        if not ok:
            clips.append(NarrationClip(spec.id, None, 0.0, spec.narration, False, detail))
            continue
        out = project.audio_dir / f"{spec.id}.wav"
        try:
            text = normalise_for_tts(spec.narration)
            dur = engine.synthesise(text, out)
            clips.append(NarrationClip(spec.id, out, dur, text, dur > 0))
        except Exception as exc:  # pragma: no cover - depends on model
            clips.append(NarrationClip(spec.id, None, 0.0, spec.narration, False, str(exc)))
    return clips


# --------------------------------------------------------------------------
# subtitles (SRT)
# --------------------------------------------------------------------------
def _ts(seconds: float) -> str:
    if seconds < 0:
        seconds = 0
    ms = int(round(seconds * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def _wrap(text: str, width: int = 42) -> str:
    words, lines, cur = text.split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > width and cur:
            lines.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    if cur:
        lines.append(cur)
    return "\n".join(lines)


def build_srt(project: ProjectConfig, clips: list[NarrationClip] | None = None,
              *, out_path: Path | None = None) -> Path:
    """Write an SRT aligned to the *assembled video* timeline.

    Cue times come from each scene's declared ``duration`` in the brief, because
    that is exactly how long the rendered scene is (``ExplainerScene.settle()``
    pads every scene to its declared duration).  Using the raw narration length
    instead would drift, since speech is usually shorter than the scene.
    """
    out_path = Path(out_path or project.build_dir / "subtitles.srt")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    entries: list[str] = []
    t = 0.0
    idx = 1
    for spec in project.scenes:
        dur = max(spec.duration, 0.5)
        start, end = t, t + dur
        text = spec.subtitle_source
        if text:
            entries.append(f"{idx}\n{_ts(start)} --> {_ts(end)}\n{_wrap(text)}\n")
            idx += 1
        t = end
    out_path.write_text("\n".join(entries), encoding="utf-8")
    return out_path


# --------------------------------------------------------------------------
# ffmpeg audio helpers
# --------------------------------------------------------------------------
def pad_audio(src: Path, dst: Path, target_duration: float, *, fade: float = 0.25) -> Path | None:
    """Pad or trim ``src`` to exactly ``target_duration`` with tiny fades."""
    if not src.exists():
        return None
    dst.parent.mkdir(parents=True, exist_ok=True)
    filt = (
        f"apad,atrim=0:{target_duration:.3f},"
        f"afade=t=in:st=0:d={fade},"
        f"afade=t=out:st={max(0.0, target_duration - fade):.3f}:d={fade}"
    )
    cmd = [
        "ffmpeg", "-y", "-v", "error", "-i", str(src),
        "-af", filt, "-ar", "44100", "-ac", "1", str(dst),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    return dst if proc.returncode == 0 and dst.exists() else None


def concat_audio(parts: list[Path], dst: Path) -> Path | None:
    """Concatenate WAV parts in order using the ffmpeg concat demuxer."""
    if not parts:
        return None
    dst.parent.mkdir(parents=True, exist_ok=True)
    listing = dst.with_suffix(".txt")
    listing.write_text(
        "\n".join(f"file '{p.resolve().as_posix()}'" for p in parts),
        encoding="utf-8",
    )
    cmd = [
        "ffmpeg", "-y", "-v", "error", "-f", "concat", "-safe", "0",
        "-i", str(listing), "-c", "copy", str(dst),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    return dst if proc.returncode == 0 and dst.exists() else None


def fit_scene_durations(
    project: ProjectConfig,
    clips: list[NarrationClip],
    *,
    tail: float = 0.6,
    min_duration: float = 3.0,
    write: bool = True,
) -> list[tuple[str, float, float]]:
    """Set each scene's duration to its real narration length plus a short tail.

    This is what removes the long silent pauses: a declared ``duration`` is only
    a guess, and if it is longer than the speech the scene holds a frozen frame
    after the voice stops.  Measuring the generated audio and fitting the scene
    to it keeps the pacing tight.

    ``tail`` is the small pause after the last word so a scene does not cut off
    abruptly.  Scenes whose animation is longer than the narration keep their
    declared duration (the visuals need the time).

    Returns a list of ``(scene_id, old_duration, new_duration)`` for the scenes
    that changed, and (when ``write``) persists the new durations to the brief's
    ``project.yaml`` so the change survives re-renders.
    """
    changes: list[tuple[str, float, float]] = []
    by_id = {c.scene_id: c for c in clips}

    for spec in project.scenes:
        clip = by_id.get(spec.id)
        if clip is None or not clip.ok or clip.duration <= 0:
            continue  # silent scene (e.g. a title card): leave it alone
        target = round(max(min_duration, clip.duration + tail), 1)
        if abs(target - spec.duration) >= 0.1:
            changes.append((spec.id, spec.duration, target))
            spec.duration = target

    if changes and write:
        _persist_durations(project)
    return changes


def _persist_durations(project: ProjectConfig) -> None:
    """Write the (possibly updated) scene durations back to project.yaml.

    Done as a targeted line edit so comments, ordering and formatting in the
    hand-authored brief survive.
    """
    import re

    yaml_path = project.root / "project.yaml"
    if not yaml_path.exists():
        return
    text = yaml_path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    current_id: str | None = None
    durations = {s.id: s.duration for s in project.scenes}

    for line in lines:
        m = re.match(r"^(\s*)-?\s*id:\s*(\S+)", line)
        if m:
            current_id = m.group(2)
        if current_id and current_id in durations:
            dm = re.match(r"^(\s*duration:\s*)(\S+)(\s*)$", line.rstrip("\n"))
            if dm:
                line = f"{dm.group(1)}{durations[current_id]:g}\n"
        out.append(line)

    yaml_path.write_text("".join(out), encoding="utf-8")


def build_narration_track(project: ProjectConfig, clips: list[NarrationClip],
                          dst: Path | None = None) -> Path | None:
    """Build a single narration track aligned to the scene timeline.

    Each clip is padded/trimmed to its scene's declared duration so the track
    lines up with the assembled video even when speech is shorter or longer.
    """
    dst = Path(dst or project.audio_dir / "narration.wav")
    parts: list[Path] = []
    for spec in project.scenes:
        clip = next((c for c in clips if c.scene_id == spec.id), None)
        # Always pad/trim to the scene's declared duration, whether or not it has
        # narration, so the track length matches the assembled video exactly.
        target = max(spec.duration, 0.5)
        if clip is None or not clip.ok or clip.path is None:
            # silence placeholder of the right length keeps alignment
            silence = project.audio_dir / f"{spec.id}_silence.wav"
            subprocess.run(
                ["ffmpeg", "-y", "-v", "error", "-f", "lavfi",
                 "-i", "anullsrc=r=44100:cl=mono", "-t",
                 f"{target:.3f}", str(silence)],
                capture_output=True, text=True,
            )
            if silence.exists():
                parts.append(silence)
            continue
        padded = project.audio_dir / f"{spec.id}_pad.wav"
        out = pad_audio(clip.path, padded, target)
        parts.append(out or clip.path)
    return concat_audio(parts, dst)
