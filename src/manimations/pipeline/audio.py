"""Narration, music and subtitle processing.

Narration is generated by one of two **local** text-to-speech backends:

* ``pocket-tts`` (Kyutai) — CPU-only, ~100M parameters; the default, and the
  only one that runs comfortably without a GPU.
* ``voxcpm`` (OpenBMB) — a larger, more expressive multilingual model with
  voice design and zero-shot voice cloning; needs PyTorch and, in practice, a
  GPU.

The backend is chosen by ``narration_engine`` in the brief or ``--engine`` on the
CLI.  Both engines share one small interface (:class:`TTSEngine`), so everything
downstream — padding, concatenation, the music bed, subtitles, muxing — is
backend-agnostic and remains plain ffmpeg.

The module degrades gracefully: if the selected backend or its model weights are
unavailable, ``synthesise_narration`` reports the failure instead of pretending
to have made audio.
"""

from __future__ import annotations

import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

from ..config import ProjectConfig, SceneSpec
from . import probe


# --------------------------------------------------------------------------
# narration text hygiene
# --------------------------------------------------------------------------
#: Expand the few symbols a TTS reads poorly so the voice sounds natural.
_READ_ALOUD = {
    "IPv4": "I P version four",
    "IPv6": "I P version six",
    "IP": "I P",
    "IETF": "I E T F",
    "IANA": "I A N A",
    "NAT": "N A T",
    "CIDR": "C I D R",
    "ISP": "I S P",
    "DNS": "D N S",
    "TCP": "T C P",
    "UDP": "U D P",
    "DHCP": "D H C P",
    "TTL": "T T L",
    "LAN": "L A N",
    "WAN": "W A N",
    "&": "and",
    "%": "percent",
    "→": " to ",
}


def normalise_for_tts(text: str) -> str:
    """Make narration friendlier for a speech model without changing meaning."""
    out = text
    for src, dst in _READ_ALOUD.items():
        out = re.sub(rf"(?<![\w]){re.escape(src)}(?![\w])", dst, out)
    out = re.sub(r"\s+", " ", out).strip()
    return out


@dataclass
class NarrationClip:
    scene_id: str
    path: Path | None
    duration: float
    text: str
    ok: bool
    error: str = ""


